def latest_run(path_str):
    """Return LaTeX-formatted latest timestamp folder name, or '---' if absent."""
    p = Path(path_str)
    if not p.exists():
        return '---'
    ts = re.compile(r'^\d{8}_\d{6}$')
    runs = sorted(d.name for d in p.iterdir() if d.is_dir() and ts.match(d.name))
    escaped = runs[-1].replace('_', r'\_')
    return f'\\texttt{{{escaped}}}' if runs else '---'


def paths(comparable_only=False, **kwargs):
    """Return (comparable_path, system_path | None) for the given experiment kwargs."""
    c = get_experiment_path(eval_mode='comparable', **kwargs)
    s = None if comparable_only else get_experiment_path(eval_mode='system', **kwargs)
    return c, s


