# provenance table can't drift out of sync with what the results/pattern_analysis
# scripts actually use. H0 has no entry of its own — it's defined as "= F1".
_ALL_KWARGS = {**SCENARIO_KWARGS, **BOOST_SCENARIO_KWARGS, "H0": SCENARIO_KWARGS["F1"]}


def row(sid, desc, comparable_only=False):
    """Build a (id, description, comparable_path, system_path) GROUPS row.
    `desc` is this table's own prose (more detailed than scenarios.py's SCENARIO_NAMES,
    which are compact labels for results tables) — kwargs are shared, descriptions aren't."""
    c, s = paths(comparable_only=comparable_only, **_ALL_KWARGS[sid])
    return (sid, desc, c, s)


