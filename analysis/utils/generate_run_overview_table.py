def build_table(groups):
    lines = []
    lines.append(r'% Auto-generated by generate_run_overview_table.py — do not edit by hand.')
    lines.append(r'% Path root: experiments/small_HI/split_0.6_0.2/{comparable|system}/...')
    lines.append(r'% Timestamps show the latest run folder; load_results.py picks the most recent.')
    lines.append(r'\begin{tabular}{llll}')
    lines.append(r'\toprule')
    lines.append(r'\textbf{ID} & \textbf{Description} & \textbf{Comparable run} & \textbf{System run} \\')

    for group_name, rows in groups:
        lines.append(r'\midrule')
        lines.append(rf'\multicolumn{{4}}{{l}}{{\textit{{{group_name}}}}} \\')
        for r in rows:
            exp_id, desc, c_path, s_path = r
            c_run = latest_run(c_path)
            s_run = latest_run(s_path) if s_path is not None else '---'
            lines.append(rf'{exp_id} & {desc} & {c_run} & {s_run} \\')

    lines.append(r'\bottomrule')
    lines.append(r'\end{tabular}')
    return '\n'.join(lines) + '\n'


